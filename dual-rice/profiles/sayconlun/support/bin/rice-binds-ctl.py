# ------------------------------------------------------------------- lua --
def tokens(text):
    out = []
    for m in TOKEN.finditer(text):
        kind = next(k for k in TOKEN_KINDS if m.group(k) is not None)
        if kind != "space":
            out.append((kind, m.group(0), m.start(), m.end()))
    return out


def split_comment(line):
    for kind, text, start, _ in tokens(line):
        if kind == "comment":
            return line[:start], text[2:].strip()
    return line, ""


def call_args(line, open_at):
    """Source text of each top-level argument of the call whose `(` is at open_at."""
    depth, args, begin = 0, [], open_at + 1
    for kind, text, start, end in tokens(line):
        if start <= open_at or kind != "op":
            continue
        if text in "({[":
            depth += 1
        elif text in ")}]":
            if depth == 0:
                args.append(line[begin:start].strip())
                return [a for a in args if a]
            depth -= 1
        elif text == "," and depth == 0:
            args.append(line[begin:start].strip())
            begin = end
    return None


def string_value(expr, variables):
    """A string literal, a variable, or `..` joins of them - else None."""
    parts, want_value = [], True
    for kind, text, _, _ in tokens(expr):
        if want_value:
            if kind == "str":
                parts.append(re.sub(r"\\(.)", r"\1", text[1:-1]))
            elif kind == "long":
                parts.append(re.sub(r"^\[=*\[\n?|\]=*\]$", "", text))
            elif kind == "name" and isinstance(variables.get(text), str):
                parts.append(variables[text])
            else:
                return None
        elif kind != "concat":
            return None
        want_value = not want_value
    return "".join(parts) if parts and not want_value else None


def lua_str(text):
    return json.dumps(text, ensure_ascii=False)


# ----------------------------------------------------------------- parsing --
def read_vars(lines):
    variables = {}
    for raw in lines:
        code, _ = split_comment(raw)
        m = LOCAL.match(code.strip())
        if m:
            value = string_value(m.group(2), variables)
            if value is not None:
                variables[m.group(1)] = value
    return variables


def action_of(expr, variables):
    m = re.match(r"^exec\((.*)\)$", expr.strip(), re.S)
    if m:
        cmd = string_value(m.group(1), variables)
        return f"exec {cmd}" if cmd is not None else expr.strip()
    flat = " ".join(expr.split())
    for pattern, text in ACTIONS:
        if re.match(pattern, flat):
            return re.sub(pattern, text, flat)
    return flat


def norm_mods(text, strict=False):
    found = set()
    for part in re.split(r"[\s_+]+", text.strip().upper()):
        if not part or part == "NONE":
            continue
        if part not in MOD_ALIASES:
            if strict:
                raise ValueError(f"unknown modifier {part}")
            found.add(part)
            continue
        found.add(MOD_ALIASES[part])
    known = [m for m in MOD_ORDER if m in found]
    return " ".join(known + sorted(found - set(MOD_ORDER)))


def norm_key(text):
    key = text.strip()
    return key.upper() if len(key) == 1 else key


def keys_string(mods, key):
    """The form hl.bind() takes: "SUPER + SHIFT + T"."""
    return " + ".join(mods.split() + [key])


def parse():
    with open(BASELINE) as f:
        lines = f.read().splitlines()
    variables = read_vars(lines)
    binds, seen, committed = [], {}, {}
    category = "General"
    for raw in lines:
        m = SECTION.match(raw.strip())
        if m:
            name = m.group(1)
            category = name[:1].upper() + name[1:]
            continue
        code, comment = split_comment(raw)
        m = BIND.match(code)          # column 0 only: the submap's hl.bind is not listed
        if not m:
            continue
        args = call_args(code, m.end() - 1)
        keys = string_value(args[0], variables) if args and len(args) >= 2 else None
        if keys is None:
            continue
        kind = m.group(1)
        parts = [p.strip() for p in keys.split("+")]
        mods, key = norm_mods(" ".join(parts[:-1])), parts[-1]
        bid = f"{kind}|{mods}|{key.lower()}"
        n = seen.get(bid, 0)
        seen[bid] = n + 1
        if n:
            bid += f"#{n}"
        nth = committed.get(keys, 0) + 1         # rice.binds[keys][nth]
        committed[keys] = nth
        binds.append({
            "id": bid, "category": category, "kind": kind,
            "committed": keys, "nth": nth,
            "base_mods": mods, "base_key": key,
            "action": action_of(args[1], variables), "comment": comment,
        })
    return binds


# ------------------------------------------------------------- presenting --
def action_text(b):
    return re.sub(
        r"(~|\$HOME|/home/[^/\s]+)/\.local/(?:bin|share/desktop-profiles/sayconlun/support/bin)/",
        "",
        b["action"],
    )


def label(b):
    action = action_text(b)
    for pattern, result in LABELS:
        m = re.search(pattern, action)
        if m:
            return result(m) if callable(result) else result
    return b["comment"] or action


def pretty_key(key):
    low = key.lower()
    if low in KEY_NAMES:
        return KEY_NAMES[low]
    if low.startswith("code:"):
        return "key " + key[5:]
    return key.upper() if len(key) == 1 else key


def keys_of(mods, key):
    return [MOD_NAMES.get(m, m.title()) for m in mods.split()] + [pretty_key(key)]


def editable(b):
    # A mouse button or wheel cannot be captured from a keyboard event.
    return b["kind"] != "bindm" and not b["base_key"].lower().startswith("mouse")


# ------------------------------------------------------------------ state --
def load_state():
    try:
        with open(OVERRIDES) as f:
            for line in f:
                if line.startswith("-- state: "):
                    return json.loads(line[len("-- state: "):])
    except (OSError, ValueError):
        pass
    return {}


def effective(b, state):
    o = state.get(b["id"])
    return (o["mods"], o["key"]) if o else (b["base_mods"], b["base_key"])


def same(a, b):
    return a[0] == b[0] and a[1].lower() == b[1].lower()


def override(state, b, mods, key):
    if same((mods, key), (b["base_mods"], b["base_key"])):
        state.pop(b["id"], None)
    else:
        state[b["id"]] = {"mods": mods, "key": key}


def rebind_call(changes):
    """changes: [(bind, mods, key)] -> one rice.rebind() call, as Lua source."""
    rows = [f"{{ {lua_str(b['committed'])}, {b['nth']}, {lua_str(keys_string(m, k))} }}"
            for b, m, k in changes]
    return "rice.rebind({ " + ", ".join(rows) + " })"


def write_overrides(binds, state):
    by = {b["id"]: b for b in binds}
    live = {i: o for i, o in state.items() if i in by}
    out = [HEADER, "-- state: " + json.dumps(live, sort_keys=True, ensure_ascii=False), ""]
    if live:
        out.append(rebind_call([(by[i], o["mods"], o["key"]) for i, o in live.items()]))
    os.makedirs(os.path.dirname(OVERRIDES), exist_ok=True)
    tmp = OVERRIDES + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(out) + "\n")
    os.replace(tmp, OVERRIDES)


def hypr_eval(code):
    try:
        r = subprocess.run([HYPRCTL, "eval", code], capture_output=True, text=True, timeout=5)
    except (OSError, subprocess.TimeoutExpired) as e:
        return str(e)
    out = r.stdout.strip()
    if r.returncode == 0 and out == "ok":
        return None
    return out or r.stderr.strip() or "hyprctl failed"


def apply_live(by, state, ids):
    # One call, so rice.rebind() unbinds everything before binding anything: in
    # a swap, one bind's new keys are the other's old ones.
    if not ids:
        return []
    err = hypr_eval(rebind_call([(by[i], *effective(by[i], state)) for i in ids]))
    return [err] if err else []


# --------------------------------------------------------------- commands --
def cmd_list(_args):
    binds, state = parse(), load_state()
    out = []
    for b in binds:
        m, k = effective(b, state)
        out.append({
            "id": b["id"], "category": b["category"], "label": label(b),
            "action": action_text(b), "kind": b["kind"], "mods": m, "key": k,
            "keys": keys_of(m, k), "base_keys": keys_of(b["base_mods"], b["base_key"]),
            "overridden": b["id"] in state, "editable": editable(b),
        })
    emit(ok=True, binds=out)


def cmd_set(args):
    binds = parse()
    by = {b["id"]: b for b in binds}
    b = by.get(args.id)
    if not b:
        emit(ok=False, error=f"no bind with id {args.id}")
    if not editable(b):
        emit(ok=False, error="mouse and scroll binds can only be changed in binds.lua")
    try:
        mods = norm_mods(args.mods, strict=True)
    except ValueError as e:
        emit(ok=False, error=str(e))
    key = norm_key(args.key)
    if not key:
        emit(ok=False, error="no key given")

    old = load_state()
    new = {i: dict(o) for i, o in old.items()}
    here = effective(b, old)
    if same(here, (mods, key)):
        emit(ok=True, message=f"{label(b)} is already {' + '.join(keys_of(mods, key))}")

    clash = [o for o in binds if o["id"] != b["id"] and same(effective(o, old), (mods, key))]
    if clash and not args.swap:
        c = clash[0]
        emit(ok=False, conflict={"id": c["id"], "label": label(c), "keys": keys_of(mods, key)})

    override(new, b, mods, key)
    ids = [b["id"]]
    for c in clash:
        override(new, c, *here)
        ids.append(c["id"])
    write_overrides(binds, new)
    warnings = apply_live(by, new, ids)

    message = f"{label(b)} → {' + '.join(keys_of(mods, key))}"
    if clash:
        message += f", {label(clash[0])} → {' + '.join(keys_of(*here))}"
    emit(ok=True, message=message, warnings=warnings)


def cmd_reset(args):
    binds = parse()
    by = {b["id"]: b for b in binds}
    old = load_state()
    ids = [i for i in ([args.id] if args.id else list(old)) if i in old and i in by]
    if not ids:
        emit(ok=True, message="Nothing to reset")

    # Anything sitting on a reset bind's committed keys - the other half of a
    # swap - has to go back too, or the reset would create a clash.
    new = {i: o for i, o in old.items() if i not in ids}
    grew = True
    while grew:
        grew = False
        for i in list(new):
            if i in by and any(same(effective(by[i], new), (by[r]["base_mods"], by[r]["base_key"])) for r in ids):
                ids.append(i)
                del new[i]
                grew = True

    write_overrides(binds, new)
    warnings = apply_live(by, new, ids)
    if len(ids) == 1:
        b = by[ids[0]]
        message = f"{label(b)} back to {' + '.join(keys_of(b['base_mods'], b['base_key']))}"
    else:
        message = f"{len(ids)} binds back to binds.lua"
    emit(ok=True, message=message, warnings=warnings)


def cmd_reapply(_args):
    binds = parse()
    by = {b["id"]: b for b in binds}
    state = {i: o for i, o in load_state().items() if i in by}
    warnings = apply_live(by, state, list(state))
    emit(ok=True, message=f"{len(state)} overrides reapplied", warnings=warnings)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list").set_defaults(fn=cmd_list)
    s = sub.add_parser("set")
    s.add_argument("id")
    s.add_argument("mods", help='e.g. "SUPER SHIFT", or "" for none')
    s.add_argument("key")
    s.add_argument("--swap", action="store_true")
    s.set_defaults(fn=cmd_set)
    r = sub.add_parser("reset")
    r.add_argument("id", nargs="?")
    r.set_defaults(fn=cmd_reset)
    sub.add_parser("reapply").set_defaults(fn=cmd_reapply)
    args = ap.parse_args(argv)
    try:
        args.fn(args)
    except OSError as e:
        emit(ok=False, error=str(e))


if __name__ == "__main__":
    main()
