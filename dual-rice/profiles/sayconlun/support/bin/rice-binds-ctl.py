#!/usr/bin/env python3
"""
Keybind control - the engine behind the Quickshell keybind menu (Super+/).

Sibling of rice-look-ctl.py and the same shape: conf/binds.lua is the
committed baseline, a change is applied live with `hyprctl eval` and
persisted to a generated conf.d/30-binds.lua that is loaded after it.
binds.lua is never rewritten.

  rice-binds-ctl.py list                          JSON: every bind, by section
  rice-binds-ctl.py set <id> "<MODS>" <KEY>       rebind; a clash is reported, not made
  rice-binds-ctl.py set <id> "<MODS>" <KEY> --swap   ...the other bind takes the old keys
  rice-binds-ctl.py reset [id]                    back to binds.lua, one or all
  rice-binds-ctl.py reapply                       push saved overrides back

Every command prints ONE line of JSON - {"ok": true, ...} or
{"ok": false, "error": ...} / {"ok": false, "conflict": {...}} - and exits 0
when it could answer, so the menu only ever has one thing to parse.

A bind's id is its COMMITTED identity, `kind|MODS|key` as written in
binds.lua. It stays the same however often the bind is moved, which is what
lets an override find its bind again after binds.lua is edited.

Moving a bind is rice.rebind() from conf/lib.lua, both live and in the
overrides file: it finds the bind by the key string it was committed with and
binds that bind's own dispatcher and flags to the new keys. So this tool only
ever READS Lua - it never has to write a dispatcher back out.

The overrides file carries its own state on a `-- state:` line, so deleting the
file really is a full reset - there is no second copy to disagree with it.
"""

